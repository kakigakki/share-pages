function romaji(k){
  let r="",i=0;
  while(i<k.length){
    const two=k.slice(i,i+2);
    if(/^[キシチニヒミリギジビピ][ャュョ]$/.test(two)){
      const base=ROMA[two[0]].replace(/i$/,"");        // shi→sh, chi→ch, ki→k, ji→j
      const v={ャ:"a",ュ:"u",ョ:"o"}[two[1]];
      // sh/ch/j は直接 a/u/o、それ以外は y を挟む（kya, nya, rya…）
      r += /(sh|ch|j)$/.test(base) ? base+v : base+"y"+v;
      i+=2; continue;
    }
    r+=ROMA[k[i]]??""; i++;
  }
  return r.charAt(0).toUpperCase()+r.slice(1);
}
function gokaku(nameChars){
  const ns=nameChars.map(x=>x.s), sum=ns.reduce((a,b)=>a+b,0);
  const ten=SEI.s+1, jin=SEI.s+ns[0], chi=ns.length>1?sum:sum+1;
  const gai=1+ns[ns.length-1], sou=SEI.s+sum;
  return {ten,jin,chi,gai,sou};
}
