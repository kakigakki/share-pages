/* 中国語の声調。何は hé（2声）＝平声。
   平＝1・2声、仄＝3・4声。姓と名が三つとも平声だと平板に聞こえる、というのが
   中国側の基本感覚（日本語には無い観点）。 */
const isPing = t => t===1 || t===2;
function toneScore(t){
  if(!t) return {sc:0,note:null,flag:null};
  const flat = isPing(t[0]) && isPing(t[1]);   // 何(平) + 平 + 平
  if(flat) return {sc:-2,note:null,flag:"中国語で読むと三つとも平声（píng）になり、平板に聞こえます"};
  return {sc:1.5,note:"声調 2-"+t.join("-")+"／起伏がある",flag:null};
}

function score(chars,yomi,opt){
  opt = opt || {};
  let sc=0, notes=[], flags=[];
  const full="カ"+yomi, mora=[...full].filter(c=>!"ャュョー".includes(c)).length;
  if(KAGYO.test(yomi)){ sc-=4; flags.push("「カ」のあとにカ行・ガ行が続いて詰まります"); }
  else sc+=1;
  if(/カ$/.test(yomi)){ sc-=2; flags.push("姓と同じ「カ」で終わり、カ…カと反復します"); }
  if(opt.cn){
    // 中国式は音読みで長くなるのが自然なので、長さでは減点しない
    notes.push("全体"+mora+"拍");
  } else if(mora>=4&&mora<=5){ sc+=3; notes.push("全体"+mora+"拍・据わりがいい"); }
  else if(mora===3){ sc-=1; notes.push("全体3拍・やや短い"); }
  else if(mora>=6){ sc-=1; notes.push("全体"+mora+"拍・やや長い"); }
  const vs=[...full].map(VOW).filter(Boolean);
  for(let i=0;i+2<vs.length;i++) if(vs[i]===vs[i+1]&&vs[i+1]===vs[i+2]){ sc-=2; flags.push("同じ母音が3つ続いて単調です"); break; }
  if(/^[アイウエオヤユヨワ]/.test(yomi)) sc+=1;
  chars.forEach(k=>{
    if(HE_WORDS[k.c]){
      flags.push("中国語で「"+HE_WORDS[k.c]+"」という既存の語になります");
      sc-=5;   // 姓と続けて既存語になるのは中国側では致命的なので重く見る
    }
    if(k.warn==="国字") flags.push(k.c+"は日本の国字で、中国語には存在しません");
    else if(k.warn) flags.push(k.c+"：中国語では「奈何・无奈」の語感があり、単独では名前に使いません");
  });
  if(opt.tones){
    const ts=toneScore(opt.tones);
    sc+=ts.sc;
    if(ts.note) notes.push(ts.note);
    if(ts.flag) flags.push(ts.flag);
  }
  return {sc,notes,flags,mora};
}

