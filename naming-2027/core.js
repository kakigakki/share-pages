function setsuDay(year,idx){ // idx:0=小寒 … 11=大雪
  const [,mo,C]=SETSU[idx], Y=year%100;
  return {m:mo, d:Math.floor(Y*0.2422+C)-Math.floor((Y-1)/4)};
}
function jdn(y,m,d){
  const a=Math.floor((14-m)/12), yy=y+4800-a, mm=m+12*a-3;
  return d+Math.floor((153*mm+2)/5)+365*yy+Math.floor(yy/4)-Math.floor(yy/100)+Math.floor(yy/400)-32045;
}
function bazi(dt){
  if(!(dt instanceof Date)||isNaN(dt)) return null;
  let y=dt.getFullYear(), mo=dt.getMonth()+1, d=dt.getDate(), h=dt.getHours(), mi=dt.getMinutes();
  // 日柱：23時以降は翌日の日柱として扱う
  let dd=new Date(dt); if(h>=23) dd.setDate(dd.getDate()+1);
  const dIdx=(jdn(dd.getFullYear(),dd.getMonth()+1,dd.getDate())+49)%60;
  // 年柱：立春で切り替え
  const ris=setsuDay(y,1);
  const afterRisshun=(mo>2)||(mo===2&&d>=ris.d);
  const yearForPillar=afterRisshun?y:y-1;
  const yIdx=((yearForPillar-4)%60+60)%60;
  // 月柱：どの節の期間にいるか
  let si=-1;
  for(let i=0;i<12;i++){
    const s=setsuDay(y,i);
    const passed=(mo>s.m)||(mo===s.m&&d>=s.d);
    if(passed) si=i;
  }
  if(si<0){ const s=setsuDay(y-1,11); si=11; } // 1月で小寒前 → 前年の大雪
  const mShi=SETSU_SHI[si];
  const yKan=yIdx%10;
  const firstTora=[2,4,6,8,0][yKan%5];              // 五虎遁：寅月の天干
  const mKan=(firstTora+((mShi-2)+12)%12)%10;
  // 時柱：五鼠遁
  const dKan=dIdx%10;
  const hShi=(h===23)?0:Math.floor((h+1)/2)%12;
  const firstNe=[0,2,4,6,8][dKan%5];
  const hKan=(firstNe+hShi)%10;
  // 節入り日ちょうどか
  const boundary=SETSU.some((_,i)=>{const s=setsuDay(y,i);return s.m===mo&&s.d===d;});
  const pil=[[yIdx%10,yIdx%12],[mKan,mShi],[dKan,dIdx%12],[hKan,hShi]];
  const cnt={"木":0,"火":0,"土":0,"金":0,"水":0};
  pil.forEach(([k,s])=>{cnt[KAN_G[k]]++;cnt[SHI_G[s]]++;});
  const min=Math.min(...GOGYO.map(g=>cnt[g]));
  return {pil,cnt,lack:GOGYO.filter(g=>cnt[g]===min),boundary,afterRisshun,risshun:ris};
}

