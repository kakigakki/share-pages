function build(S,d,t){
  const bz=(S.bazi&&d)?bazi(new Date(d+"T"+(t||"12:00"))):null;
  const dict=Object.fromEntries(K.map(k=>[k.c,k]));
  const okSex=(a,b)=>a==="n"||b==="n"||a===b;
  const want=(sx)=>S.sex==="n"||sx===S.sex||sx==="n";
  const cand=[];

  // 中国式：日本の「語幹＋止め字」とは作り方が違うので、別リストから足す
  if(S.style!=="jp"){
    CN.forEach(nm=>{
      const cs=[...nm.n].map(c=>dict[c]);
      if(cs.some(x=>!x)) return;
      if(S.era && S.era!=="all" && nm.era!==S.era) return;
      cand.push({chars:cs,yomi:nm.y,sex:nm.sex,kind:"中国式",era:nm.era,
                 py:nm.py,tones:nm.t,src:nm.src,note:nm.note});
    });
  }
  // 一字名：プールの漢字のうち、上の字として読みを持つもの
  if(S.len!==2 && S.style!=="cn"){
    SOLO.forEach(([c,r,sx])=>{
      const k=dict[c]; if(!k) return;
      cand.push({chars:[k],yomi:r,sex:sx,kind:"一字"});
    });
  }
  // 二字名：上の字 × 止め字。日本語の名前が実際に作られる形に沿って組む
  if(S.len!==1 && S.style!=="cn"){
    FIRST.forEach(([c1,r1,s1])=>{
      const k1=dict[c1]; if(!k1) return;
      LAST.forEach(([c2,r2,s2])=>{
        const k2=dict[c2]; if(!k2) return;
        if(c1===c2) return;                              // 同じ字の重複
        if(!okSex(s1,s2)) return;                        // 男の字＋女の止め字は組まない
        if(r1[r1.length-1]===r2[0]) return;              // 接合部で同じ仮名が重なる
        const y=r1+r2;
        const mora=[...y].filter(c=>!"ャュョー".includes(c)).length;
        if(mora<2||mora>4) return;                       // 名は2〜4拍（姓が1拍のため）
        cand.push({chars:[k1,k2],yomi:y,sex:(s1==="n"?s2:s1),kind:"二字"});
      });
    });
  }

  const out=[];
  cand.forEach(o=>{
    if(!want(o.sex)) return;
    if(S.pop && o.chars.some(k=>k.pop>=2)) return;
    const g=gokaku(o.chars), sc=score(o.chars,o.yomi,{cn:o.kind==="中国式",tones:o.tones});
    let total=sc.sc;
    if(S.kaku){ [g.jin,g.chi,g.sou].forEach(v=>total+=isKichi(v)?1.5:-1); }
    if(bz){ o.chars.forEach(k=>{ if(bz.lack.includes(k.g)) total+=2.5; }); }
    if(S.pop) o.chars.forEach(k=>total-=k.pop*1.5);
    // 日本式には拍数の加点(+3)が付くが中国式には付かない。
    // 混ぜて並べるときだけ、その差を埋めて同じ土俵に乗せる。
    if(S.style!=="cn" && o.kind==="中国式") total+=3;
    out.push({...o,g,s:sc,total,bz});
  });
  out.sort((x,y)=>y.total-x.total);
  const seen=new Set(), uniq=[];
  for(const o of out){
    const key=o.chars.map(c=>c.c).join("")+"/"+o.yomi;
    if(seen.has(key)) continue; seen.add(key); uniq.push(o);
  }
  return {list:uniq,bz,total:uniq.length};
}

