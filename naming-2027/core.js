function romaji(k){
  let r="",i=0;
  while(i<k.length){
    const two=k.slice(i,i+2);
    if(/^[キシチニヒミリギジビピ][ャュョ]$/.test(two)){
      const base=ROMA[two[0]].replace(/i$/,"");        // shi→sh, chi→ch, ki→k, ji→j
      const v={ャ:"a",ュ:"u",ョ:"o"}[two[1]];
      // sh/ch/j は直接 a/u/o、それ以外は y を挟む（kya, nya, rya…）
      r += /(sh|ch|j)$/.test(base) ? base+v : base+"y"+v;
      i+=2; continue;
    }
    r+=ROMA[k[i]]??""; i++;
  }
  return r.charAt(0).toUpperCase()+r.slice(1);
}
function gokaku(nameChars){
  const ns=nameChars.map(x=>x.s), sum=ns.reduce((a,b)=>a+b,0);
  const ten=SEI.s+1, jin=SEI.s+ns[0], chi=ns.length>1?sum:sum+1;
  const gai=1+ns[ns.length-1], sou=SEI.s+sum;
  return {ten,jin,chi,gai,sou};
}
const isKichi=n=>KICHI.has(((n-1)%81)+1);

function score(chars,yomi){
  let sc=0, notes=[], flags=[];
  const full="カ"+yomi, mora=[...full].filter(c=>!"ャュョー".includes(c)).length;
  if(KAGYO.test(yomi)){ sc-=4; flags.push("「カ」のあとにカ行・ガ行が続いて詰まります"); }
  else sc+=1;
  if(/カ$/.test(yomi)){ sc-=2; flags.push("姓と同じ「カ」で終わり、カ…カと反復します"); }
  if(mora>=4&&mora<=5){ sc+=3; notes.push("全体"+mora+"拍・据わりがいい"); }
  else if(mora===3){ sc-=1; notes.push("全体3拍・やや短い"); }
  else if(mora>=6){ sc-=1; notes.push("全体"+mora+"拍・やや長い"); }
  const vs=[...full].map(VOW).filter(Boolean);
  for(let i=0;i+2<vs.length;i++) if(vs[i]===vs[i+1]&&vs[i+1]===vs[i+2]){ sc-=2; flags.push("同じ母音が3つ続いて単調です"); break; }
  if(/^[アイウエオヤユヨワ]/.test(yomi)) sc+=1;
  chars.forEach(k=>{
    if(HE_WORDS[k.c]) flags.push("中国語で「"+HE_WORDS[k.c]+"」という既存の語になります");
    if(k.warn==="国字") flags.push(k.c+"は日本の国字で、中国語には存在しません");
    else if(k.warn) flags.push(k.c+"：中国語では「奈何・无奈」の語感があり、単独では名前に使いません");
  });
  return {sc,notes,flags,mora};
}

